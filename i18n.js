window.pickLang = function (supported) {
  const q = new URLSearchParams(location.search).get("lang");
  const cands = [q, ...(navigator.languages || [navigator.language])].filter(Boolean).map((l) => l.slice(0, 2).toLowerCase());
  return cands.find((l) => supported.includes(l) && I18N[l]) || "es";
};

window.fmt = (s, vars = {}) => s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");

// iframe: zgłaszamy wysokość stronie-rodzicowi (embed.js)
window.reportHeight = function () {
  if (window.parent === window) return;
  const h = document.documentElement.scrollHeight;
  window.parent.postMessage({ type: "reservas:height", height: h }, "*");
};
new ResizeObserver(() => window.reportHeight()).observe(document.documentElement);
